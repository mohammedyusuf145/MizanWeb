let lang = 'ar';
export const getLang = () => lang;
export const dirOf = (l = lang) => (l === 'ar' ? 'rtl' : 'ltr');

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'ar';
  const root = document.documentElement;
  root.lang = lang;
  root.dir = dirOf(lang);
  try { localStorage.setItem('proof.lang', lang); } catch { /* storage unavailable */ }
}

export function initialLang() {
  try { const s = localStorage.getItem('proof.lang'); if (s === 'ar' || s === 'en') return s; } catch { /* ignore */ }
  return 'ar'; // Arabic by default
}

/** t('key', {vars}) → string. Missing keys fall back to the other language, then the key. */
export function t(key, vars = {}) {
  let v = T[lang][key];
  if (v === undefined) v = T[lang === 'ar' ? 'en' : 'ar'][key];
  if (v === undefined) { console.warn('[i18n] missing', key); return key; }
  if (typeof v === 'function') return v(vars);
  if (Array.isArray(v)) return v;
  return v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
